// Generates src/lib/docs-index.ts — a LIGHTWEIGHT {slug,title,category}[] for the command palette,
// extracted from the heavy src/lib/docs-data.ts (~338 KB) so the palette can search every doc page
// WITHOUT bundling the full docs content on every page. Re-run this whenever docs-data.ts changes:
//   node scripts/gen-docs-index.cjs
const fs = require("fs");
const path = require("path");

const SRC = path.join(__dirname, "..", "src", "lib", "docs-data.ts");
const OUT = path.join(__dirname, "..", "src", "lib", "docs-index.ts");

const src = fs.readFileSync(SRC, "utf8");

// pass 1: every `const PAGE_X: DocPage = { slug: "...", title: "..."` → varName -> {slug,title}
const byVar = {};
const pageRe = /const\s+(PAGE_\w+)\s*:\s*DocPage\s*=\s*\{\s*slug:\s*"([^"]+)",\s*title:\s*"([^"]+)"/g;
let m;
while ((m = pageRe.exec(src))) byVar[m[1]] = { slug: m[2], title: m[3] };

// pass 2: each category `{ name: "...", pages: [PAGE_A, PAGE_B, ...] }` → category for those vars
const entries = [];
const seen = new Set();
const catRe = /name:\s*"([^"]+)",\s*pages:\s*\[([^\]]*)\]/g;
let c;
while ((c = catRe.exec(src))) {
  const category = c[1];
  for (const v of c[2].split(",").map((s) => s.trim()).filter(Boolean)) {
    if (byVar[v] && !seen.has(v)) {
      seen.add(v);
      entries.push({ ...byVar[v], category });
    }
  }
}
// fallback: if the category structure didn't parse, index every page under "Documentation"
if (entries.length === 0) {
  for (const v of Object.keys(byVar)) entries.push({ ...byVar[v], category: "Documentation" });
}

const esc = (s) => s.replace(/\\/g, "\\\\").replace(/"/g, '\\"');
const lines = entries
  .map((e) => `  { slug: "${esc(e.slug)}", title: "${esc(e.title)}", category: "${esc(e.category)}" },`)
  .join("\n");

const out = `// SPDX-License-Identifier: LicenseRef-PYRAX-Proprietary
//
// GENERATED by scripts/gen-docs-index.cjs from docs-data.ts — do not edit by hand.
// A lightweight title/slug index of every docs page, so the command palette can search docs
// without importing the heavy docs-data.ts on every page. Re-run the generator when docs change.
export type DocIndexEntry = { slug: string; title: string; category: string };
export const DOC_INDEX: DocIndexEntry[] = [
${lines}
];
`;

fs.writeFileSync(OUT, out, "utf8");
console.log(`docs-index.ts written: ${entries.length} pages`);
